#!/usr/bin/env node
// dsh-gsd build — stage GSD assets into the plugin package.
//
// PRODUCTION source (P1, ROADMAP 01-01): `@opengsd/gsd-core@<GSD_VERSION>` npm
// tarball. Main chain: fetch (online `npm pack`) → pre-gate (fetched ==
// requested, BEFORE staging) → official installer `--claude --global` staging
// passthrough (CLAUDE_CONFIG_DIR = throwaway mktemp dir, HOME =
// .gsd-build-tmp/fakehome) → 4-tree whitelist capture (skills/gsd-* + gsd-core
// + hooks + scripts; config/ comes from the committed canonical template
// build/assets/gsd-hooks.json; settings.json / agents / .gsd-* are NEVER
// copied) → staging-root-based path rewrite → DSH adapter-note injection (72
// SKILL.md) → dual gates (product version / residual absolute paths / adapter
// counts).
//
// GSD_BUILD_SOURCE is a LEGACY SPIKE compatibility entry ONLY (separate branch
// below); the main path never reads it.
//
// Exit codes: 0 ok (staging + fakehome cleaned) / 1 IO·unpack·installer failure
// (staging tree kept for forensics) / 2 gate failure (blocks prepack).
import { cp, mkdir, mkdtemp, readFile, readdir, rm, writeFile } from 'node:fs/promises'
import { existsSync } from 'node:fs'
import { spawnSync } from 'node:child_process'
import { createHash } from 'node:crypto'
import { homedir } from 'node:os'
import { dirname, join, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'
import { makeRewrites } from './build/lib/rewrite-map.cjs'

const root = resolve(dirname(fileURLToPath(import.meta.url)))
const PLUGIN_ROOT_REF = '$DSH_PROFILE_DIR/node_modules/dsh-gsd'

// Single exit funnel for the whole file (main path + legacy branch).
const finish = (code, msg) => {
  if (msg) (code === 0 ? console.log : console.error)(msg)
  process.exit(code)
}

// Trimmed env access — an empty string counts as unset.
const env = (name) => (process.env[name] || '').trim()

const NOTE = `<!-- gsd:dsh-adapter begin (generated by dsh-gsd build) -->

<runtime_note>
**DeepSeek Harness (DSH) plugin note.** 本技能由 \`dsh-gsd\` 插件提供;技能正文面向 Claude Code 编写,在 DSH 中按下表平移:
- 所有路径引用中的 \`$DSH_PROFILE_DIR\` 前缀 = 本插件的安装位置。用 bash 执行一次
  \`echo $DSH_PROFILE_DIR/node_modules/dsh-gsd\` 得到实际绝对路径 GSDROOT 后,
  后续 read/grep/glob 一律用 GSDROOT 替换该前缀再操作(一次展开,全程复用)。
- 引擎命令: \`node <GSDROOT>/gsd-core/bin/gsd-tools.cjs <verb> ...\`(等价于官方 CLI \`gsd_run\`;
  在 bash 块内可先 \`gsd_run() { node <GSDROOT>/gsd-core/bin/gsd-tools.cjs "$@"; }\` 定义函数后沿用 \`gsd_run <verb>\`)。
  无需 \`npm i -g\`。
- \`Agent\` / \`Task\`(按名派发子代理)→ 本会话的 \`subagent\` 工具。DSH 不注册 \`agents/*.md\`:
  派发某角色前先 \`read\` \`<GSDROOT>/gsd-core/agents/gsd-<role>.md\`(存在 \`.compact.md\` 优先读它),
  把其中的 \`<role>\` / \`<required_reading>\` / \`<config>\` 原文放进子代理 prompt。
  frontmatter 的 tools 白名单与 model 档位在 DSH 不生效,由 prompt 纪律替代。
  一条消息中并行发起多个 \`subagent\` 调用即“同一波并行执行”;子代理结果不会自动回传,按
  \`job_output\` 或直接同步调用收集,并始终按文件系统与 git 状态做完成核对(工作流已有该回退)。
- \`Skill\`→\`skill\`;\`AskUserQuestion\`→\`ask_user_question\`;\`TodoWrite\`→\`todo_write\`;
  \`WebSearch\`→\`web_search\`;\`WebFetch\`→\`web_fetch\`;\`Bash\`→\`bash\`;\`Grep\`→\`grep\`;\`Glob\`→\`glob\`;
  \`Read\`→\`read\`;\`Write\`→\`write\`;\`Edit\`→\`edit\`。
- 本文件与工作流中的 \`@<path>\` 不会被宿主自动展开:把它们当作需按需 \`read\` 的文件清单(渐进披露,
  并按上文把 \`$DSH_PROFILE_DIR\` 前缀替换为 GSDROOT)。
- \`$ARGUMENTS\` 占位符不会被宿主替换:从本条用户消息原文解析参数。
- \`mcp__*\` 工具仅在用户为 DSH 配置了对应 MCP 服务时存在;否则按工作流给出的 CLI/Bash 回退执行。
</runtime_note>

<!-- gsd:dsh-adapter end -->`

// Both marker forms occur in the wild:
//   <!-- gsd:dsh-adapter begin -->            (installer template)
//   <!-- gsd:dsh-adapter begin (regenerated by install-gsd-dsh.sh) -->  (deployed)
const ADAPTER_BLOCK = /<!-- gsd:dsh-adapter begin[^\n]*-->[\s\S]*?<!-- gsd:dsh-adapter end -->\s*/g

function stripAdapter(raw) {
  return raw.replace(ADAPTER_BLOCK, '')
}

function rewrite(text, rewrites, counters) {
  let out = text
  for (const [from, to] of rewrites) {
    if (out.includes(from)) { out = out.split(from).join(to); counters.rewritten++ }
  }
  return out
}

async function walk(dir, fn) {
  const entries = await readdir(dir, { withFileTypes: true })
  for (const e of entries) {
    const p = join(dir, e.name)
    if (e.isDirectory()) await walk(p, fn)
    else if (e.isFile()) await fn(p)
  }
}

async function injectNote(files, counters) {
  for (const f of files) {
    let raw = await readFile(f, 'utf8')
    raw = stripAdapter(raw)
    const lines = raw.split('\n')
    let count = 0, at = -1
    for (let i = 0; i < lines.length; i++) {
      if (lines[i].replace(/\r$/, '') === '---') {
        count++
        if (count === 2) { at = i; break }
      }
    }
    if (at < 0) { console.error(`build: no frontmatter in ${f}`); continue }
    lines.splice(at + 1, 0, ...NOTE.split('\n'))
    await writeFile(f, lines.join('\n'))
    counters.notes++
  }
}

// ---------------------------------------------------------------------------
// Legacy SPIKE branch (compat only — behaviour unchanged from the SPIKE build)
// ---------------------------------------------------------------------------
async function legacyBuild(source, sourceHome) {
  const rewrites = [
    [`${sourceHome}/gsd-core`, `${PLUGIN_ROOT_REF}/gsd-core`],
    [`${sourceHome}/skills`, `${PLUGIN_ROOT_REF}/skills`],
    [`${sourceHome}/tasks`, '$DSH_HOME/tasks'],
    [sourceHome, '$DSH_HOME'],
    ['~/.dsh/gsd-core', `${PLUGIN_ROOT_REF}/gsd-core`],
    ['~/.dsh/tasks', '$DSH_HOME/tasks'],
    ['~/.dsh', '$DSH_HOME'],
  ]
  const counters = { copied: 0, rewritten: 0, notes: 0 }
  console.log(`build: source=${source} from-prefix=${sourceHome}`)
  for (const d of ['skills', 'gsd-core', 'hooks', 'config', 'scripts']) {
    await rm(join(root, d), { recursive: true, force: true })
  }
  const skillNames = []
  for (const e of await readdir(join(source, 'skills'))) {
    if (!e.startsWith('gsd-')) continue
    skillNames.push(e)
    await cp(join(source, 'skills', e), join(root, 'skills', e), { recursive: true })
    counters.copied++
  }
  await cp(join(source, 'gsd-core'), join(root, 'gsd-core'), { recursive: true })
  counters.copied++
  await cp(join(source, 'hooks'), join(root, 'hooks'), { recursive: true })
  counters.copied++
  await cp(join(source, 'scripts'), join(root, 'scripts'), { recursive: true })
  counters.copied++
  await mkdir(join(root, 'config'), { recursive: true })
  await cp(join(source, 'gsd-hooks.dsh.json'), join(root, 'config', 'gsd-hooks.json'))
  counters.copied++
  for (const tree of ['skills', 'gsd-core', 'scripts']) {
    await walk(join(root, tree), async (f) => {
      await writeFile(f, rewrite(await readFile(f, 'utf8'), rewrites, counters))
    })
  }
  const skillFiles = skillNames.map((n) => join(root, 'skills', n, 'SKILL.md'))
  await injectNote(skillFiles, counters)
  console.log(`build: copied ${counters.copied} trees, rewrote paths in ${counters.rewritten} files, injected notes into ${counters.notes} skills (${skillNames.length} total)`)
}

// ---------------------------------------------------------------------------
// Offline tier chain helpers
// ---------------------------------------------------------------------------
// ① 档完整性对照（T-1-01）：读 THIRD-PARTY-NOTICES.md 中该 GSD_VERSION 行的
// canonical 值，对 tarball 做 SHA-512（对照 dist.integrity 解码值）与 SHA-1
// （对照 dist.shasum）双重比对。未记录 / 任一不符 → exit 2 fail-closed。
async function checkTarballIntegrity(tgzPath, version) {
  const notices = await readFile(join(root, 'THIRD-PARTY-NOTICES.md'), 'utf8')
  const tableRows = notices
    .split('\n').map((l) => l.trim())
    .filter((l) => l.startsWith('| @opengsd/gsd-core |'))
  const row = tableRows.find((l) => l.startsWith(`| @opengsd/gsd-core | ${version} |`))
  if (!row) {
    finish(2, `build: checksum mismatch (expected <sha512> per THIRD-PARTY-NOTICES.md: no record for @opengsd/gsd-core@${version})`)
  }
  const cells = row.split('|').map((c) => c.trim())
  const shasum = cells[3]
  const integrity = cells[4]
  const buf = await readFile(tgzPath)
  const sha512hex = createHash('sha512').update(buf).digest('hex')
  const sha1hex = createHash('sha1').update(buf).digest('hex')
  const expected512 = Buffer.from(integrity.replace(/^sha512-/, ''), 'base64').toString('hex')
  if (sha512hex !== expected512 || sha1hex !== shasum) {
    finish(2, `build: checksum mismatch (expected ${expected512} sha512 / ${shasum} sha1 per THIRD-PARTY-NOTICES.md)`)
  }
  console.log('build: GSD_TARBALL integrity verified against THIRD-PARTY-NOTICES.md')
}

async function fetchEngine(GSD_VERSION, WORK) {
  // 探测顺序固定（01-RESEARCH Pattern 2），命中即止。
  // ① GSD_TARBALL（显式档，shasum-gated）→ ② .build-cache（repo 内缓存）
  // → ③ GSD_PACKAGE_DIR（unpacked；必须含 bin/install.js 与 package.json）
  // → ④ npm pack（在线）。npm cache 离线模式永不进入代码路径（ENOTCACHED 实测，
  // RESEARCH Pitfall 1——镜像 302 重定向使缓存键落在 cdn URL 上）。
  console.log(`build: fetching @opengsd/gsd-core@${GSD_VERSION}`)
  const tarballEnv = env('GSD_TARBALL')
  const cacheTgz = join(root, '.build-cache', `opengsd-gsd-core-${GSD_VERSION}.tgz`)
  const pkgDirEnv = env('GSD_PACKAGE_DIR')
  let tgzPath = null
  let tier = ''

  if (tarballEnv) {
    tgzPath = resolve(process.cwd(), tarballEnv)
    tier = 'GSD_TARBALL'
    await checkTarballIntegrity(tgzPath, GSD_VERSION)
  } else if (existsSync(cacheTgz)) {
    tgzPath = cacheTgz
    tier = '.build-cache'
  } else if (pkgDirEnv) {
    const p = resolve(process.cwd(), pkgDirEnv)
    if (existsSync(join(p, 'bin', 'install.js')) && existsSync(join(p, 'package.json'))) {
      tier = 'GSD_PACKAGE_DIR'
      console.log(`build: fetched via ${tier} (unpacked — no tar step)`)
      return { pkgDir: p, tier }
    }
  }

  if (!tgzPath) {
    // ④ online npm pack（最后一档）
    const r = spawnSync('npm', ['pack', `@opengsd/gsd-core@${GSD_VERSION}`, '--pack-destination', WORK, '--silent'], { stdio: 'inherit' })
    if (r.status !== 0) {
      finish(1, `build: could not fetch @opengsd/gsd-core@${GSD_VERSION} — no offline tier available (tried in order: ① GSD_TARBALL, ② .build-cache/opengsd-gsd-core-${GSD_VERSION}.tgz, ③ GSD_PACKAGE_DIR) and ④ online npm pack failed (exit ${r.status}). offline? see BUILD.md`)
    }
    tgzPath = join(WORK, `opengsd-gsd-core-${GSD_VERSION}.tgz`)
    tier = 'npm pack'
  }
  console.log(`build: fetched via ${tier}; unpacking with system tar`)
  await rm(join(WORK, 'package'), { recursive: true, force: true })
  const t = spawnSync('tar', ['xzf', tgzPath, '-C', WORK], { stdio: 'inherit' })
  if (t.error) finish(1, `build: tar unavailable (need system tar/bsdtar for unpacking) — ${t.error.message}`)
  if (t.status !== 0) finish(1, `build: tar unpack of ${tgzPath} failed (exit ${t.status})`)
  return { pkgDir: join(WORK, 'package'), tier }
}

// ---------------------------------------------------------------------------
// Production path: npm tarball → official staging → capture → rewrite →
// inject → gates.
// ---------------------------------------------------------------------------
async function main() {
  // ① GSD_VERSION（默认 1.20.1；格式强校验）
  const GSD_VERSION = env('GSD_VERSION') || '1.20.1'
  if (!/^\d+\.\d+\.\d+$/.test(GSD_VERSION)) {
    finish(2, `build: invalid GSD_VERSION '${GSD_VERSION}' (must match \\d+\\.\\d+\\.\\d+)`)
  }
  const WORK = join(root, '.gsd-build-tmp')
  await mkdir(WORK, { recursive: true })

  // ② fetch: 离线三档 → 在线（探测顺序固定，命中即止）
  const { pkgDir: PKG_DIR } = await fetchEngine(GSD_VERSION, WORK)

  // ③ pre-gate (BEFORE staging): fetched == requested
  {
    const p = spawnSync('node', ['-p', `require(${JSON.stringify(join(PKG_DIR, 'package.json'))}).version`], { encoding: 'utf8' })
    const fetched = (p.stdout || '').trim()
    if (p.status !== 0 || fetched !== GSD_VERSION) {
      finish(2, `build: fetched version ${fetched || '(unreadable)'} != requested ${GSD_VERSION}`)
    }
  }

  // ④ staging via the official installer (never hand-rolled)
  console.log('build: staging with the official installer (claude passthrough)')
  let STAGING
  const FAKEHOME = join(WORK, 'fakehome')
  {
    STAGING = await mkdtemp(join(WORK, 'staging.'))
    await mkdir(FAKEHOME, { recursive: true })
    const r = spawnSync('node', [join(PKG_DIR, 'bin', 'install.js'), '--claude', '--global'], {
      // CLAUDE_CONFIG_DIR pins the installer to the throwaway staging dir; fake
      // HOME keeps the run reproducible; PATH explicitly inherited.
      env: { ...process.env, CLAUDE_CONFIG_DIR: STAGING, HOME: FAKEHOME, PATH: process.env.PATH },
      stdio: 'inherit',
    })
    if (r.status !== 0) {
      finish(1, `build: official installer failed (exit ${r.status}) — staging kept at ${STAGING} for forensics`)
    }
  }

  // ⑤ capture: whitelist copy of exactly 4 trees（settings.json / agents / .gsd-* 概不拷贝）
  console.log('build: capturing 4-tree whitelist')
  const counters = { copied: 0, rewritten: 0, notes: 0 }
  for (const d of ['skills', 'gsd-core', 'hooks', 'config', 'scripts']) {
    await rm(join(root, d), { recursive: true, force: true })
  }
  const skillNames = []
  for (const e of await readdir(join(STAGING, 'skills'))) {
    if (!e.startsWith('gsd-')) continue
    skillNames.push(e)
    await cp(join(STAGING, 'skills', e), join(root, 'skills', e), { recursive: true })
    counters.copied++
  }
  await cp(join(STAGING, 'gsd-core'), join(root, 'gsd-core'), { recursive: true })
  counters.copied++
  await cp(join(STAGING, 'hooks'), join(root, 'hooks'), { recursive: true })
  counters.copied++
  await cp(join(STAGING, 'scripts'), join(root, 'scripts'), { recursive: true })
  counters.copied++
  await mkdir(join(root, 'config'), { recursive: true })
  await cp(join(root, 'build', 'assets', 'gsd-hooks.json'), join(root, 'config', 'gsd-hooks.json'))
  counters.copied++

  // ⑥ rewrite: from-basis = THIS run's staging root（不是任何部署前缀，无 /Users/
  // 字面量依赖）。映射来自 build/lib/rewrite-map.cjs（可单测模块：staging 根
  // 基准 + ~/ 与 $HOME 回退形态，最长/最具体 from 在前）。
  const rewrites = makeRewrites(STAGING)
  for (const tree of ['skills', 'gsd-core', 'hooks', 'scripts']) {
    await walk(join(root, tree), async (f) => {
      await writeFile(f, rewrite(await readFile(f, 'utf8'), rewrites, counters))
    })
  }

  // ⑦ adapter injection: strip both historical markers → inject NOTE → count
  console.log('build: injecting DSH adapter notes')
  const skillFiles = skillNames.map((n) => join(root, 'skills', n, 'SKILL.md'))
  await injectNote(skillFiles, counters)
  if (skillNames.length !== 72) {
    finish(2, `build: gate failed — expected 72 gsd-* skills, got ${skillNames.length}`)
  }

  // ⑧a gate A: product version cross-check. 1.20.1 ships no gsd-core/package.json
  // (1.16.0 did) — the staged engine self-reports identity instead, and the
  // tarball's package.json version was already pinned by pre-gate ③. Verified
  // anchors in the captured tree: gsd-core/VERSION + the identity CLI's JSON.
  const verFile = (await readFile(join(root, 'gsd-core', 'VERSION'), 'utf8')).trim()
  if (verFile !== GSD_VERSION) {
    finish(2, `build: gate failed — product VERSION ${verFile} != requested ${GSD_VERSION}`)
  }
  const ident = spawnSync('node', [join(root, 'gsd-core', 'bin', 'gsd-tools.cjs'), 'runtime-identity', '--raw'], { encoding: 'utf8' })
  let identJson = null
  try { identJson = JSON.parse((ident.stdout || '').trim()) } catch { identJson = null }
  if (ident.status !== 0 || !identJson || identJson.packageName !== '@opengsd/gsd-core' || identJson.version !== GSD_VERSION) {
    finish(2, `build: gate failed — engine identity ${(ident.stdout || '').trim() || '(unavailable)'} != @opengsd/gsd-core@${GSD_VERSION}`)
  }

  // ⑧b gate B: machine-coupling scan of the product trees.
  // Three probes, each fail-closed (exit 2 on any hit):
  //  B1 staging-root prefix in ALL product trees（staging 残留）;
  //  B2 THIS machine's absolute residue in all trees（homedir() 前缀；以 root
  //     运行构建时 homedir()==/root，天然覆盖 root 形态）;
  //     upstream 1.20.1 ships narrative example paths（如 docs 里 "/Users/john/"
  //     与 "/root/.ssh" 教学举例），这些是可移植叙述、非本机残留，不能一刀切误杀（Pitfall 5 精神）;
  //  B3 literal /Users|home/<name>/ syntax in the skills/ tree only — SKIL-04
  //     的字面范围就是 SKILL.md（REQUIREMENTS.md），skills 内零容忍。
  //  $HOME/`~` 形态不在拒绝集（Pitfall 5，回退改写目标）。
  const escapeRe = (s) => s.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')
  const trees = ['skills', 'gsd-core', 'hooks', 'scripts'].map((t) => join(root, t))
  const gateScans = [
    [`staging prefix (4 trees)`, escapeRe(STAGING), trees],
    [`machine residue (4 trees)`, escapeRe(homedir()), trees],
    [`portable-syntax residue (skills/)`, '/(Users|home)/[A-Za-z0-9_.-]+/', [join(root, 'skills')]],
  ]
  for (const [label, pattern, scanTrees] of gateScans) {
    const g = spawnSync('grep', ['-RInE', pattern, ...scanTrees], { encoding: 'utf8' })
    if (g.error) finish(1, `build: grep unavailable for gate B — ${g.error.message}`)
    if (g.status === 0) finish(2, `build: gate failed (${label}) — residual paths matching ${pattern}:\n${g.stdout}`)
    if (g.status !== 1) finish(1, `build: gate B scan failed (${label}, grep exit ${g.status})`)
  }

  // ⑧c gate C: 72 SKILL.md files, each with exactly one adapter block
  for (const f of skillFiles) {
    const n = ((await readFile(f, 'utf8')).match(/gsd:dsh-adapter begin/g) || []).length
    if (n !== 1) finish(2, `build: gate failed — ${n} adapter blocks in ${f}`)
  }

  // ⑨ exit 0: clean staging + fakehome; last line keeps the "skills (72 total)" marker
  await rm(STAGING, { recursive: true, force: true })
  await rm(FAKEHOME, { recursive: true, force: true })
  finish(0, `build: fetched @opengsd/gsd-core@${GSD_VERSION}, copied ${counters.copied} trees, rewrote paths in ${counters.rewritten} files, injected notes into ${counters.notes} skills (${skillNames.length} total)`)
}

const legacySource = env('GSD_BUILD_SOURCE')
if (legacySource) {
  console.log('build: legacy GSD_BUILD_SOURCE path (compat only)')
  await legacyBuild(legacySource, env('GSD_BUILD_FROM') || legacySource)
    .catch((e) => finish(1, `build: legacy build failed — ${e?.message ?? e}`))
  process.exit(0)
}
await main().catch((e) => finish(1, `build: unexpected failure — ${e?.message ?? e}`))
